#!/usr/bin/env node
// Path: .claude/hooks/block-protected.js
//
// PreToolUse (Edit|Write): blocks edits to protected paths.
//
// This replaces an inline shell hook that was DEAD for two independent reasons,
// both found by probe (writing to deploy/ and watching it succeed):
//   1. it read `$TOOL_INPUT_FILE_PATH`, a variable Claude Code does not set.
//      The tool input arrives as JSON on stdin. The var was empty, so the
//      grep matched nothing and every write passed.
//   2. it used `exit 1` to block. Exit 1 is a NON-blocking error; blocking
//      needs exit 2, or exit 0 with a permissionDecision:"deny" payload.
// Either bug alone was enough. A guard that never fires is worse than none:
// it buys confidence without buying protection.
//
// Verify after any change to this file, do not assume: write to a protected
// path and confirm the tool call is refused.

const PROTEGIDOS = [
    // Lockfile: regenerated by npm, never edited by hand.
    /(^|\/)package-lock\.json$/,
    // Real secrets only. `.env.example` is a tracked template and IS editable,
    // which the old regex (a bare `\.env`) got wrong.
    /(^|\/)\.env(\.[A-Za-z0-9_-]+)?$/,
    // Deploy scripts run against the production host.
    /(^|\/)deploy\//,
    // Third-party bundles, not our source.
    /(^|\/)public\/vendors\//,
];

const EXCECOES = [/(^|\/)\.env\.example$/];

let bruto = '';
process.stdin.on('data', (c) => (bruto += c));
process.stdin.on('end', () => {
    let caminho = '';
    try {
        caminho = (JSON.parse(bruto).tool_input || {}).file_path || '';
    } catch {
        // Malformed payload: fail OPEN. A parser bug here must not brick every
        // edit in the repo. The cost of a missed block is lower than the cost
        // of a hook that refuses everything.
        process.exit(0);
    }

    const normalizado = caminho.replace(/\\/g, '/');
    const isento = EXCECOES.some((re) => re.test(normalizado));
    const protegido = !isento && PROTEGIDOS.some((re) => re.test(normalizado));

    if (protegido) {
        process.stdout.write(
            JSON.stringify({
                hookSpecificOutput: {
                    hookEventName: 'PreToolUse',
                    permissionDecision: 'deny',
                    permissionDecisionReason:
                        `Arquivo protegido (${normalizado}). Edite manualmente, ` +
                        `ou justifique e peça ao usuário. Ver .claude/hooks/block-protected.js`,
                },
            })
        );
    }
    process.exit(0);
});
